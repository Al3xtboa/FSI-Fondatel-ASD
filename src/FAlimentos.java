    private void BRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRegistrarActionPerformed

        // Agrega esto al inicio:
        if (cartel == null) {
            JOptionPane.showMessageDialog(this, "Por favor selecciona un cartel primero.");
            return; // Detiene la ejecución para que no intente guardar
        }

        String cla = TClave.getText();
        String tit = Ttitulo.getText();
        ImageIcon car = cartel;

        Alimento pp = new Alimento(cla, tit, foto);
        if (pp.insertar(cnx)==1) {
            cnx.entablar("SELECT * FROM peliculas", TConsultas);
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar");
        }

    }//GEN-LAST:event_BRegistrarActionPerformed

